#!/usr/bin/env node
/**
 * build-articles.mjs
 * ------------------------------------------------------------------
 * Dependency-free static generator for the Articles section.
 *
 *   node scripts/build-articles.mjs [--root <dir>]
 *
 * Reads   content/categories.json and content/articles/<slug>.json
 * Writes  articles/index.html                       (always)
 *         articles/<slug>/index.html                (published only)
 *         articles/category/<slug>/index.html       (categories with >= 1 published article)
 * Updates the article block in sitemap.xml and the generator-owned JSON-LD
 * hashes in netlify.toml (the CSP stays strict: hashes, never 'unsafe-inline').
 *
 * Drafts are never written, listed, linked or put in the sitemap.
 * Output is committed and served as plain static files by Netlify.
 * ------------------------------------------------------------------
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const argRoot = process.argv.indexOf("--root");
const ROOT = resolve(argRoot > -1 ? process.argv[argRoot + 1] : join(dirname(fileURLToPath(import.meta.url)), ".."));

const SITE = "https://www.bizora-cm.com";
const VERSION = readFileSync(join(ROOT, "VERSION"), "utf8").trim();
const DEFAULT_OG_IMAGE = `${SITE}/assets/images/og-cover.6e3fe7b6.png`;
const MARKER = "<!-- generated by scripts/build-articles.mjs — do not edit by hand -->";
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const GENERIC_ANCHORS = /^(click here|here|read more|more|link)$/i;

const read = (p) => readFileSync(join(ROOT, p), "utf8");
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const sha = (s) => createHash("sha256").update(s).digest("base64");
const fmtDate = (d) => { const [y, m, day] = d.split("-").map(Number); return `${day} ${MONTHS[m - 1]} ${y}`; };

const errors = [];
const fail = (m) => errors.push(m);


/* Featured image: local WebP, declared size must match the file, and small. */
const MAX_IMAGE_BYTES = 200 * 1024;
function webpSize(buf) {
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WEBP") return null;
  const t = buf.toString("ascii", 12, 16);
  if (t === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (t === "VP8L") { const b = buf.readUInt32LE(21); return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1]; }
  if (t === "VP8X") return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1];
  return null;
}
function checkImage(id, fi) {
  if (!fi.src || !fi.alt || !fi.width || !fi.height) return fail(`${id}: featuredImage needs src, alt, width and height`);
  if (!fi.src.startsWith("/assets/") || !fi.src.endsWith(".webp")) return fail(`${id}: featuredImage.src must be a local /assets/….webp file`);
  const file = join(ROOT, fi.src);
  if (!existsSync(file)) return fail(`${id}: featuredImage file not found: ${fi.src}`);
  const buf = readFileSync(file);
  if (buf.length > MAX_IMAGE_BYTES) fail(`${id}: featuredImage is ${(buf.length / 1024).toFixed(0)} KB (max ${MAX_IMAGE_BYTES / 1024} KB)`);
  const dim = webpSize(buf);
  if (!dim) fail(`${id}: featuredImage is not a valid WebP`);
  else if (dim[0] !== Number(fi.width) || dim[1] !== Number(fi.height)) fail(`${id}: featuredImage declared ${fi.width}x${fi.height} but file is ${dim[0]}x${dim[1]}`);
}

/* ---------------------------------------------------------------- load */
const categories = JSON.parse(read("content/categories.json"));
const catBySlug = new Map(categories.map((c) => [c.slug, c]));
if (catBySlug.size !== categories.length) fail("categories.json: duplicate category slug");

const dir = join(ROOT, "content/articles");
const all = [];
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json") && !f.startsWith("_")).sort()) {
  let a;
  try { a = JSON.parse(readFileSync(join(dir, f), "utf8")); } catch (e) { fail(`${f}: invalid JSON (${e.message})`); continue; }
  const id = `content/articles/${f}`;
  for (const k of ["slug", "title", "description", "category", "datePublished", "dateModified", "author", "lang", "status"]) {
    if (typeof a[k] !== "string" || !a[k].trim()) fail(`${id}: missing "${k}"`);
  }
  if (a.slug !== f.replace(/\.json$/, "")) fail(`${id}: slug must equal the file name`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(a.slug || "")) fail(`${id}: invalid slug`);
  if (!catBySlug.has(a.category)) fail(`${id}: unknown category "${a.category}"`);
  if (!["draft", "published"].includes(a.status)) fail(`${id}: status must be draft or published`);
  if (!["en", "fr"].includes(a.lang)) fail(`${id}: lang must be en or fr`);
  for (const k of ["datePublished", "dateModified"]) if (!/^\d{4}-\d{2}-\d{2}$/.test(a[k] || "")) fail(`${id}: ${k} must be YYYY-MM-DD`);
  if (a.dateModified < a.datePublished) fail(`${id}: dateModified is earlier than datePublished`);
  a.faq = Array.isArray(a.faq) ? a.faq : [];
  a.relatedArticles = Array.isArray(a.relatedArticles) ? a.relatedArticles : [];
  a.seo = a.seo || {};
  if (a.status === "published") {
    if (a.lang !== "en") fail(`${id}: only lang "en" can be published (French pages/hreflang are not enabled yet)`);
    let body = a.content;
    const bodyFile = join(dir, `${a.slug}.html`);
    if ((body === undefined || body === null) && existsSync(bodyFile)) body = readFileSync(bodyFile, "utf8");
    if (typeof body !== "string" || !body.trim()) fail(`${id}: published article has no content`);
    a._body = body || "";
    if (/class="[^"]*\b(section|feature-card)\b/.test(a._body)) fail(`${id}: body must not use the scroll-reveal classes "section"/"feature-card"`);
    if (a._body.includes("<!--faq-->") && !a.faq.length) fail(`${id}: <!--faq--> placeholder used but no faq entries`);
    if (/<h1[\s>]/i.test(a._body)) fail(`${id}: body must not contain an <h1> (the title is the H1)`);
    for (const m of a._body.matchAll(/<a\b[^>]*>([\s\S]*?)<\/a>/gi)) {
      if (GENERIC_ANCHORS.test(m[1].replace(/<[^>]+>/g, "").trim())) fail(`${id}: generic link text "${m[1].trim()}"`);
    }
    for (const q of a.faq) if (!q || !q.question || !q.answer) fail(`${id}: each faq item needs question and answer`);
    const canon = `${SITE}/articles/${a.slug}/`;
    if (a.seo.canonical && a.seo.canonical !== canon) fail(`${id}: seo.canonical must be ${canon}`);
    if (a.featuredImage) checkImage(id, a.featuredImage);
  }
  all.push(a);
}
if (new Set(all.map((a) => a.slug)).size !== all.length) fail("duplicate article slug");
const published = all.filter((a) => a.status === "published").sort((x, y) => y.datePublished.localeCompare(x.datePublished) || x.slug.localeCompare(y.slug));
const pubBySlug = new Map(published.map((a) => [a.slug, a]));
for (const a of published) for (const r of a.relatedArticles) {
  if (!pubBySlug.has(r)) {
    const draft = all.find((x) => x.slug === r);
    if (!draft) fail(`content/articles/${a.slug}.json: relatedArticles references unknown slug "${r}"`);
    else console.warn(`warning: ${a.slug}: related article "${r}" is a draft and is not linked`);
  }
}
if (errors.length) { console.error("Generator errors:\n - " + errors.join("\n - ")); process.exit(1); }

/* ------------------------------------------------- shared JSON-LD nodes */
const aboutLd = JSON.parse(read("pages/about.html").match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
const orgNode = aboutLd["@graph"].find((n) => n["@type"] === "Organization");
const siteNode = aboutLd["@graph"].find((n) => n["@type"] === "WebSite");
if (!orgNode || !siteNode) { console.error("pages/about.html: Organization/WebSite JSON-LD not found"); process.exit(1); }

const generated = new Map(); // relative path -> html
const hashes = new Map();    // hash -> page path

function ldScript(graph, pagePath) {
  const inner = "\n" + JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/<\/script/gi, "<\\/script") + "\n  ";
  hashes.set(sha(inner), pagePath);
  return `<script type="application/ld+json">${inner}</script>`;
}

const crumbList = (items) => ({
  "@type": "BreadcrumbList",
  itemListElement: items.map(([name, url], i) => ({ "@type": "ListItem", position: i + 1, name, item: url }))
});

/* ------------------------------------------------------------ templates */
function page({ path, title, description, ogTitle, ogDescription, ogImage, ogType, canonical, robots, graph, bodyHtml, extraMeta = "", lang = "en" }) {
  return `<!DOCTYPE html>
<html lang="${lang}">
<head>
  ${MARKER}
  <meta name="site-version" content="${VERSION}" />
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />${robots ? `\n  <meta name="robots" content="${robots}" />` : ""}

  <!-- Open Graph -->
  <meta property="og:title" content="${esc(ogTitle)}" />
  <meta property="og:description" content="${esc(ogDescription)}" />
  <meta property="og:type" content="${ogType}" />
  <meta property="og:image" content="${esc(ogImage)}" />
  <meta property="og:url" content="${canonical}" />
  <link rel="canonical" href="${canonical}" />${extraMeta}

  <!-- Twitter/X card -->
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${esc(ogTitle)}" />
  <meta name="twitter:description" content="${esc(ogDescription)}" />
  <meta name="twitter:image" content="${esc(ogImage)}" />

  <link rel="icon" type="image/x-icon" href="/assets/icons/favicon.ico" />
  <link rel="icon" type="image/png" sizes="32x32" href="/assets/icons/favicon-32x32.png" />
  <link rel="icon" type="image/png" sizes="16x16" href="/assets/icons/favicon-16x16.png" />
  <link rel="apple-touch-icon" href="/assets/icons/apple-touch-icon.png" />

  <link rel="stylesheet" href="/css/main.css" />
  <link rel="stylesheet" href="/css/components.css" />
  <link rel="stylesheet" href="/css/responsive.css" />
  <link rel="stylesheet" href="/css/articles.css" />

  ${ldScript(graph, path)}
</head>
<body>
  <div data-component="navbar"></div>
  <noscript>
    <nav class="article-noscript" aria-label="Site links">
      <a href="/">Bizora home</a> <a href="/articles/">Business guides and articles</a> <a href="/pages/features.html">Bizora features</a> <a href="/pages/pricing.html">Bizora pricing</a> <a href="/pages/support.html">Bizora support</a>
    </nav>
  </noscript>

  <main id="main-content" class="articles">
    <div class="container">
${bodyHtml}
    </div>
  </main>

  <div data-component="footer"></div>

  <!-- No animations.js here: article text must never wait on, or be hidden by, scroll-reveal. -->
  <script src="/config/site-config.js"></script>
  <script src="/js/main.js"></script>
  <script src="/js/navigation.js"></script>
  <script src="/js/analytics.js"></script>
</body>
</html>
`;
}

const breadcrumbHtml = (items) => `      <nav class="breadcrumb" aria-label="Breadcrumb">
        <ol>
${items.map(([name, href], i) => i === items.length - 1
  ? `          <li><span aria-current="page">${esc(name)}</span></li>`
  : `          <li><a href="${href}">${esc(name)}</a></li>`).join("\n")}
        </ol>
      </nav>`;

const catUrl = (c) => `/articles/category/${c.slug}/`;
const artUrl = (a) => `/articles/${a.slug}/`;

function cardHtml(a) {
  const cat = catBySlug.get(a.category);
  return `        <li>
          <article class="article-card">
            <p class="article-card__category">${esc(cat.name)}</p>
            <h2><a href="${artUrl(a)}">${esc(a.title)}</a></h2>
            <p class="article-card__date"><time datetime="${a.datePublished}">${fmtDate(a.datePublished)}</time></p>
            <p>${esc(a.description)}</p>
            <a class="article-card__more" href="${artUrl(a)}" aria-label="Read article: ${esc(a.title)}">Read article</a>
          </article>
        </li>`;
}

const listHtml = (items) => `      <ul class="article-list">\n${items.map(cardHtml).join("\n")}\n      </ul>`;
const usedCats = categories.filter((c) => published.some((a) => a.category === c.slug));
const catNavHtml = (current) => usedCats.length < 1 ? "" : `      <nav aria-label="Article categories">
        <ul class="article-cats">
${usedCats.map((c) => `          <li><a href="${catUrl(c)}"${c.slug === current ? ' aria-current="page"' : ""}>${esc(c.name)}</a></li>`).join("\n")}
        </ul>
      </nav>`;

/* ---------------------------------------------------------- articles index */
{
  const path = "articles/index.html";
  const url = `${SITE}/articles/`;
  const empty = published.length === 0;
  const intro = "Bizora provides practical guidance for small business owners: how to make a sale and issue a receipt, keep track of stock, follow up customer debts, know your real profit and keep simple, reliable business records.";
  const body = `      <div class="articles__wrap articles__wrap--wide">
${breadcrumbHtml([["Home", "/"], ["Articles", "/articles/"]])}
        <h1>Bizora Business Guides &amp; Articles</h1>
        <p class="articles__intro">${esc(intro)}</p>
${empty
  ? `        <div class="articles-empty">
          <p>New business guides are being prepared and will appear here soon.</p>
          <p>In the meantime, see <a href="/pages/features.html">what the Bizora point of sale (POS) and business management app can do</a> or read <a href="/pages/faq.html">answers to common questions about Bizora</a>.</p>
        </div>`
  : catNavHtml("") + "\n" + listHtml(published)}
      </div>`;
  const lastMod = published.reduce((m, a) => (a.dateModified > m ? a.dateModified : m), "");
  generated.set(path, page({
    path, canonical: url, ogType: "website", ogImage: DEFAULT_OG_IMAGE,
    title: "Bizora Business Guides & Articles",
    description: "Practical guides and articles for small business owners from Bizora: sales and POS, stock, customer debts, profit, receipts, records and business software in Cameroon.",
    ogTitle: "Bizora Business Guides & Articles",
    ogDescription: "Practical guidance for small business owners: sales, stock, customer debts, profit and business records.",
    // An empty index is a thin page: keep it crawlable but out of the index until there is content.
    robots: empty ? "noindex, follow" : "",
    graph: [orgNode, siteNode, {
      "@type": "CollectionPage", "@id": `${url}#webpage`, url, name: "Bizora Business Guides & Articles",
      inLanguage: "en", isPartOf: { "@id": siteNode["@id"] }
    }],
    bodyHtml: body
  }));
  generated.get(path); // lastMod used by sitemap below
  var indexLastMod = lastMod;
}

/* --------------------------------------------------------- category pages */
const catLastMod = new Map();
for (const c of usedCats) {
  const path = `articles/category/${c.slug}/index.html`;
  const url = `${SITE}${catUrl(c)}`;
  const items = published.filter((a) => a.category === c.slug);
  catLastMod.set(c.slug, items.reduce((m, a) => (a.dateModified > m ? a.dateModified : m), ""));
  const body = `      <div class="articles__wrap articles__wrap--wide">
${breadcrumbHtml([["Home", "/"], ["Articles", "/articles/"], [c.name, catUrl(c)]])}
        <h1>${esc(c.name)}: Bizora Business Guides</h1>
        <p class="articles__intro">${esc(c.description)}</p>
${catNavHtml(c.slug)}
${listHtml(items)}
        <p class="article-back"><a href="/articles/">Back to all Bizora business guides and articles</a></p>
      </div>`;
  generated.set(path, page({
    path, canonical: url, ogType: "website", ogImage: DEFAULT_OG_IMAGE,
    title: `${c.name}: Bizora Business Guides`,
    description: c.description.length > 160 ? c.description.slice(0, 157).replace(/\s+\S*$/, "") + "…" : c.description,
    ogTitle: `${c.name}: Bizora Business Guides`,
    ogDescription: c.description.length > 160 ? c.description.slice(0, 157).replace(/\s+\S*$/, "") + "…" : c.description,
    graph: [orgNode, siteNode,
      { "@type": "CollectionPage", "@id": `${url}#webpage`, url, name: `${c.name}: Bizora Business Guides`, inLanguage: "en", isPartOf: { "@id": siteNode["@id"] } },
      crumbList([["Home", `${SITE}/`], ["Articles", `${SITE}/articles/`], [c.name, url]])],
    bodyHtml: body
  }));
}

/* ----------------------------------------------------------- article pages */
// The featured image is the article's above-the-fold hero, so it is NOT
// lazy-loaded: it loads eagerly with fetchpriority="high" and explicit
// width/height (no layout shift). Articles without an image emit nothing.
for (const a of published) {
  const path = `articles/${a.slug}/index.html`;
  const url = `${SITE}${artUrl(a)}`;
  const cat = catBySlug.get(a.category);
  const seo = a.seo;
  const imgAbs = a.featuredImage ? SITE + a.featuredImage.src : null;
  const ogImage = seo.ogImage || imgAbs || DEFAULT_OG_IMAGE;
  const title = seo.metaTitle || `${a.title} | Bizora`;
  const description = seo.metaDescription || a.description;

  let related = a.relatedArticles.map((s) => pubBySlug.get(s)).filter((r) => r && r.slug !== a.slug);
  if (!related.length) related = published.filter((r) => r.category === a.category && r.slug !== a.slug).slice(0, 3);

  const modified = a.dateModified !== a.datePublished;
  const crumbs = [["Home", "/"], ["Articles", "/articles/"], [cat.name, catUrl(cat)], [a.title, artUrl(a)]];
  const faqHtml = a.faq.length ? `
        <section class="article-faq" aria-labelledby="faq-heading">
          <h2 id="faq-heading">Frequently asked questions</h2>
${a.faq.map((q) => `          <h3>${esc(q.question)}</h3>\n          <p>${esc(q.answer)}</p>`).join("\n")}
        </section>` : "";
  const relatedHtml = related.length ? `
        <aside class="article-related" aria-labelledby="related-heading">
          <h2 id="related-heading">Related articles</h2>
          <ul>
${related.map((r) => `            <li><a href="${artUrl(r)}">${esc(r.title)}</a></li>`).join("\n")}
          </ul>
        </aside>` : "";
  // Optional <!--faq--> placeholder: put the visible FAQ section inside the body
  // (default: after it). Splits the body in two blocks around the FAQ.
  const block = (html) => `          <div class="article__body">\n${html.trim()}\n          </div>`;
  let bodyAndFaq;
  if (a._body.includes("<!--faq-->")) {
    const [before, after] = a._body.split("<!--faq-->");
    bodyAndFaq = block(before) + faqHtml + (after.trim() ? "\n" + block(after) : "");
  } else bodyAndFaq = block(a._body) + faqHtml;
  const body = `      <div class="articles__wrap">
${breadcrumbHtml(crumbs)}
        <article class="article">
          <header>
            <p class="article__category"><a href="${catUrl(cat)}">${esc(cat.name)}</a></p>
            <h1>${esc(a.title)}</h1>
            <p class="article__meta">By <span>${esc(a.author)}</span> · Published <time datetime="${a.datePublished}">${fmtDate(a.datePublished)}</time>${modified ? ` · Updated <time datetime="${a.dateModified}">${fmtDate(a.dateModified)}</time>` : ""}</p>${a.featuredImage ? `
            <img class="article__image" src="${esc(a.featuredImage.src)}" alt="${esc(a.featuredImage.alt)}" width="${a.featuredImage.width}" height="${a.featuredImage.height}" fetchpriority="high" decoding="async" />` : ""}
          </header>
${bodyAndFaq}
        </article>${relatedHtml}
        <p class="article-back"><a href="/articles/">Back to all Bizora business guides and articles</a> · <a href="${catUrl(cat)}">More ${esc(cat.name)} guides</a></p>
      </div>`;

  const graph = [orgNode, siteNode, {
    "@type": "Article", "@id": `${url}#article`,
    mainEntityOfPage: { "@type": "WebPage", "@id": url },
    headline: a.title, description, inLanguage: a.lang,
    datePublished: a.datePublished, dateModified: a.dateModified,
    author: { "@type": "Organization", name: a.author, url: `${SITE}/` },
    publisher: { "@id": orgNode["@id"] },
    articleSection: cat.name,
    ...(imgAbs ? { image: imgAbs } : {})
  }, crumbList([["Home", `${SITE}/`], ["Articles", `${SITE}/articles/`], [cat.name, `${SITE}${catUrl(cat)}`], [a.title, url]])];
  if (a.faq.length) graph.push({
    "@type": "FAQPage", "@id": `${url}#faq`,
    mainEntity: a.faq.map((q) => ({ "@type": "Question", name: q.question, acceptedAnswer: { "@type": "Answer", text: q.answer } }))
  });

  generated.set(path, page({
    path, canonical: url, ogType: "article", ogImage, title, description,
    ogTitle: seo.ogTitle || a.title, ogDescription: seo.ogDescription || description, graph, bodyHtml: body,
    extraMeta: `\n  <meta property="article:published_time" content="${a.datePublished}" />\n  <meta property="article:modified_time" content="${a.dateModified}" />\n  <meta property="article:section" content="${esc(cat.name)}" />`
  }));
}

/* ----------------------------------------------------------- write / prune */
function walk(d) {
  if (!existsSync(d)) return [];
  return readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
}
for (const f of walk(join(ROOT, "articles"))) {
  const rel = f.slice(ROOT.length + 1);
  if (rel.endsWith("index.html") && !generated.has(rel) && readFileSync(f, "utf8").includes(MARKER)) rmSync(f);
}
(function pruneEmpty(d) {
  if (!existsSync(d)) return;
  for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) pruneEmpty(p); }
  if (d !== join(ROOT, "articles") && readdirSync(d).length === 0) rmSync(d, { recursive: true });
})(join(ROOT, "articles"));
for (const [rel, html] of generated) {
  mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
  writeFileSync(join(ROOT, rel), html);
}

/* ------------------------------------------------------------------ sitemap */
{
  const S = "<!-- articles:start (generated) -->", E = "<!-- articles:end -->";
  let xml = read("sitemap.xml");
  xml = xml.replace(new RegExp(`\\n  ${S.replace(/[()]/g, "\\$&")}[\\s\\S]*?${E}`), "");
  if (published.length) {
    const entry = (loc, lastmod, freq, prio) => `  <url>\n    <loc>${SITE}${loc}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <changefreq>${freq}</changefreq>\n    <priority>${prio}</priority>\n  </url>`;
    const block = [S,
      entry("/articles/", indexLastMod, "weekly", "0.6"),
      ...usedCats.map((c) => entry(catUrl(c), catLastMod.get(c.slug), "weekly", "0.5")),
      ...published.map((a) => entry(artUrl(a), a.dateModified, "monthly", "0.7")),
      E].map((l, i, arr) => (i === 0 || i === arr.length - 1 ? "  " + l : l)).join("\n");
    xml = xml.replace("\n</urlset>", `\n${block}\n</urlset>`);
  }
  writeFileSync(join(ROOT, "sitemap.xml"), xml);
}

/* --------------------------------------------------------- netlify.toml CSP */
{
  let toml = read("netlify.toml");
  const B = "# ARTICLES-JSONLD-HASHES (generated by scripts/build-articles.mjs — do not edit by hand)";
  const BE = "# END ARTICLES-JSONLD-HASHES\n";
  const blockRe = new RegExp(`${B.replace(/[()]/g, "\\$&")}[\\s\\S]*?${BE}`);
  const old = toml.match(blockRe);
  const owned = old ? [...old[0].matchAll(/#\s+sha256-(\S+)/g)].map((m) => m[1]) : [];
  toml = toml.replace(blockRe, "");
  const cspRe = /(Content-Security-Policy = ")([^"]+)(")/;
  let csp = toml.match(cspRe)[2];
  for (const h of owned) csp = csp.replace(` 'sha256-${h}'`, "");
  const have = new Set([...csp.matchAll(/'sha256-([^']+)'/g)].map((m) => m[1]));
  const mine = [...hashes].filter(([h]) => !have.has(h));
  const anchor = " https://www.googletagmanager.com";
  if (!csp.includes(anchor)) { console.error("netlify.toml: CSP script-src anchor not found"); process.exit(1); }
  csp = csp.replace(anchor, mine.map(([h]) => ` 'sha256-${h}'`).join("") + anchor);
  toml = toml.replace(cspRe, (_, a, __, c) => a + csp + c);
  if (mine.length) {
    const lines = mine.map(([h, p]) => `#   sha256-${h}\n#     ${p}`).join("\n");
    toml = toml.replace("[[headers]]\n  for = \"/*\"", `${B}\n${lines}\n${BE}[[headers]]\n  for = "/*"`);
  }
  writeFileSync(join(ROOT, "netlify.toml"), toml);
}

